// Price Action Rating study: calibration and forward returns by grade.
// Usage: node --no-warnings --use-system-ca scripts/backtest-rating.mjs [--write]
// Samples every 5th session of every liquid stock (the live floor), rates it on
// candles up to that day only, and measures the next 20 and 60 sessions' return
// against that day's median. --write regenerates src/lib/screen/priceActionCalibration.ts
// so that 85+ is about the top 5%, 70+ the top 20%, 50+ the top half and 35+ the top 75%.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { Worker, isMainThread, parentPort, workerData } from "node:worker_threads";
import { cpus } from "node:os";
import { ROOT, dayNo, loadBacktestData } from "./backtest-common.mjs";

const CFG = { warmup: 260, step: 5, turnoverCr: 5, horizons: [20, 60] };
const TARGETS = [[0, 0], [0.25, 35], [0.5, 50], [0.8, 70], [0.95, 85], [1, 100]];

if (isMainThread) await main();
else await work();

async function main() {
  const t0 = Date.now();
  const { hist, floor } = loadBacktestData(CFG);
  const symbols = [...hist.keys()].filter((s) => hist.get(s).length > CFG.warmup + 5);
  const n = Math.max(1, Math.min(cpus().length - 2, 14));
  const chunks = Array.from({ length: n }, (_, k) => symbols.filter((_, i) => i % n === k));
  const parts = await Promise.all(chunks.map((chunk) => new Promise((resolve, reject) => {
    const w = new Worker(fileURLToPath(import.meta.url), { workerData: { items: chunk.map((s) => [s, hist.get(s), floor.get(s)]), CFG } });
    w.on("message", resolve);
    w.on("error", reject);
  })));
  const rows = parts.flat();
  console.log(`${rows.length} ratings over ${symbols.length} stocks in ${((Date.now() - t0) / 1000).toFixed(0)}s`);

  const raws = rows.map((r) => r.raw).sort((a, b) => a - b);
  const q = (p) => raws[Math.min(raws.length - 1, Math.max(0, Math.round(p * (raws.length - 1))))];
  const knots = [];
  for (const [p, y] of TARGETS) {
    const x = p === 0 ? 0 : p === 1 ? 100 : Math.round(q(p) * 10) / 10;
    if (!knots.length || x > knots.at(-1)[0]) knots.push([x, y]);
  }
  console.log("Raw quantiles:", TARGETS.map(([p]) => `p${p * 100}=${q(p).toFixed(1)}`).join("  "));
  console.log("Calibration knots:", JSON.stringify(knots));

  const { calibrate, paGrade } = await import("../src/lib/screen/priceActionRating.ts");
  for (const r of rows) r.grade = paGrade(Math.round(calibrate(r.raw, knots)));

  // Excess return against the median of stocks rated the same day.
  for (const h of CFG.horizons) {
    const byDay = new Map();
    for (const r of rows) if (r[`f${h}`] != null) (byDay.get(r.day) ?? byDay.set(r.day, []).get(r.day)).push(r[`f${h}`]);
    const median = new Map([...byDay].map(([d, list]) => { const s = list.sort((a, b) => a - b); return [d, s[s.length >> 1]]; }));
    for (const r of rows) if (r[`f${h}`] != null) r[`x${h}`] = r[`f${h}`] - median.get(r.day);
  }
  const days = [...new Set(rows.map((r) => r.day))].sort((a, b) => a - b);
  const mid = days[days.length >> 1];
  const fmt = (x) => (x >= 0 ? "+" : "") + x.toFixed(2);
  const stat = (list, key) => {
    const v = list.map((r) => r[key]).filter((x) => x != null);
    return v.length ? `${fmt(v.reduce((a, b) => a + b, 0) / v.length).padStart(6)}% ${String(Math.round((v.filter((x) => x > 0).length / v.length) * 100)).padStart(3)}%+` : "     -      ";
  };
  console.log(`\nForward excess return vs the day's median (mean, share positive). Split at ${new Date(mid * 864e5).toISOString().slice(0, 10)}`);
  console.log(`${"Grade".padEnd(6)}${"Samples".padStart(9)}  ${"20d all".padEnd(14)}${"20d 1st".padEnd(14)}${"20d 2nd".padEnd(14)}${"60d all".padEnd(14)}${"60d 1st".padEnd(14)}${"60d 2nd".padEnd(14)}`);
  for (const g of ["A+", "A", "B", "C", "D"]) {
    const l = rows.filter((r) => r.grade === g);
    const a = l.filter((r) => r.day < mid), b = l.filter((r) => r.day >= mid);
    console.log(`${g.padEnd(6)}${String(l.length).padStart(9)}  ${stat(l, "x20").padEnd(14)}${stat(a, "x20").padEnd(14)}${stat(b, "x20").padEnd(14)}${stat(l, "x60").padEnd(14)}${stat(a, "x60").padEnd(14)}${stat(b, "x60").padEnd(14)}`);
  }

  if (process.argv.includes("--write")) {
    const file = join(ROOT, "src", "lib", "screen", "priceActionCalibration.ts");
    const body = knots.map(([x, y]) => `  [${x}, ${y}],`).join("\n");
    writeFileSync(file, `// Generated by \`node scripts/backtest-rating.mjs --write\`; do not edit by hand.
// Raw-to-calibrated knots so that 85+ is roughly the top 5% of liquid stocks,
// 70+ the top 20%, 50+ the top half and 35+ the top 75%.
// Fitted on ${rows.length} ratings, ${new Date(days[0] * 864e5).toISOString().slice(0, 10)} to ${new Date(days.at(-1) * 864e5).toISOString().slice(0, 10)}.
export const PA_CALIBRATION: ReadonlyArray<readonly [number, number]> = [
${body}
];
`);
    console.log(`\nWrote ${file}`);
  }
}

async function work() {
  const { items, CFG: cfg } = workerData;
  const { priceActionRating } = await import("../src/lib/screen/priceActionRating.ts");
  const identity = [[0, 0], [100, 100]];
  const out = [];
  for (const [, c, floor] of items) {
    for (let i = cfg.warmup; i < c.length; i += cfg.step) {
      if (!floor[i]) continue;
      const turn = c.slice(i - 49, i + 1).map((k) => (k.close * k.volume) / 1e7).sort((a, b) => a - b);
      const turnover = (turn[24] + turn[25]) / 2;
      const r = priceActionRating(c.slice(0, i + 1), turnover, identity);
      if (r.status !== "rated") continue;
      const fwd = (h) => (i + h < c.length ? (c[i + h].close / c[i].close - 1) * 100 : null);
      out.push({ day: dayNo(c[i].t), raw: r.raw, f20: fwd(20), f60: fwd(60) });
    }
  }
  parentPort.postMessage(out);
}
